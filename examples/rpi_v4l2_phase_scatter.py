def prepare_scatter_payload(
    frame: dict[str, np.ndarray],
    *,
    point_size: float,
) -> dg.ScatterPayload:
    if payload_mode == "xyz":
        return dg.Scatter3D.prepare_points(
            frame,
            x="x",
            y="y",
            z="z",
            colormap="turbo",
        )
    return dg.Scatter3D.prepare_points(
        frame,
        x="x",
        y="y",
        z="z",
        scalars="phase",
        colormap="turbo",
        point_size=point_size,
        nan_color=(0.03, 0.03, 0.03),
    )


