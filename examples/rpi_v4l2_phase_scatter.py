def make_phase_payload(raw: np.ndarray) -> dg.ScatterPayload:
    planes = []
    header_words = max(0, int(args.packet_header_words))
    for frame_index in range(args.frames):
        start = frame_index * args.width * packet_rows + header_words
        end = start + args.width * args.image_height
        planes.append(raw[start:end].reshape(args.image_height, args.width))

    data = np.stack(planes, axis=2).astype(np.float32, copy=False)
    centered = data - np.mean(data, axis=2, keepdims=True)
    q = data[:, :, 3] - data[:, :, 1]
    i = data[:, :, 0] - data[:, :, 2]
    phase = np.arctan2(q, i).astype(np.float32, copy=False)
    intensity = np.log10(np.sum(np.abs(centered) + 1.0, axis=2))

    phase_flat = phase.reshape(-1).copy()
    threshold = float(state["threshold"])
    phase_flat[intensity.reshape(-1) <= threshold] = np.nan
    phase_sample = phase_flat[sample_idx].astype(np.float32, copy=False)

    frame = {
        "x": x_sample,
        "y": y_sample,
        "z": phase_sample * np.float32(z_scale),
        "phase": phase_sample,
    }
    return prepare_scatter_payload(frame, point_size=1.5)


