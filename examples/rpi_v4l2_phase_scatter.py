def make_fake_payload(kind: str) -> dg.ScatterPayload:
    if kind == "noise":
        x_values = debug_rng.uniform(-float(x_center), float(x_center), size=debug_points).astype(
            np.float32
        )
        y_values = debug_rng.uniform(-float(y_center), float(y_center), size=debug_points).astype(
            np.float32
        )
    else:
        x_values = debug_x_sample
        y_values = debug_y_sample
    x_norm = (x_values + x_center) / max(1.0, float(args.width - 1))
    y_norm = (y_center - y_values) / max(1.0, float(args.image_height - 1))
    if kind == "wave":
        phase = np.sin(x_norm * TAU * 4.0) + np.cos(y_norm * TAU * 3.0)
    elif kind == "rings":
        cx = x_norm - 0.5
        cy = y_norm - 0.5
        radius = np.sqrt(cx * cx + cy * cy)
        phase = np.sin(radius * TAU * 10.0)
    elif kind == "noise":
        phase = debug_rng.uniform(-np.pi, np.pi, size=debug_points)
    else:
        phase = np.linspace(-np.pi, np.pi, debug_points, dtype=np.float32)

    phase = np.asarray(phase, dtype=np.float32)
    phase = np.clip(phase, -np.pi, np.pi)
    frame = {
        "x": x_values,
        "y": y_values,
        "z": phase * np.float32(z_scale),
        "phase": phase,
    }
    return prepare_scatter_payload(frame, point_size=3.2)


def get_fake_payload(kind: str) -> dg.ScatterPayload:
    with debug_payloads_lock:
        payload = debug_payloads.get(kind)
    if payload is None:
        payload = make_fake_payload(kind)
        with debug_payloads_lock:
            debug_payloads[kind] = payload
    return payload


def apply_fake_payload(kind: str, payload: dg.ScatterPayload) -> None:
    scatter.set_prepared_points(payload, coalesce=True, update_metadata=False, fit=False)
    state["frames"] += 1
    state["last_pack_ms"] = payload.pack_ms
    state["last_points"] = payload.point_count
    status.set_value(
        f"debug {kind}: points={payload.point_count} pack={payload.pack_ms:.2f}ms"
    )


def inject_fake_points(kind: str) -> None:
    with debug_payloads_lock:
        cached = debug_payloads.get(kind)
    if cached is not None:
        apply_fake_payload(kind, cached)
        return

    status.set_value(f"building debug {kind}...")

    def worker() -> None:
        payload = get_fake_payload(kind)
        app.call_soon_threadsafe(lambda: apply_fake_payload(kind, payload))

    threading.Thread(target=worker, name=f"fake-scatter-{kind}", daemon=True).start()


def schedule_debug_reinject(kind: str, count: int, interval_ms: int) -> None:
    count = max(0, int(count))
    if count <= 0:
        return
    interval_s = max(1, int(interval_ms)) / 1000.0

    def worker() -> None:
        payload = get_fake_payload(kind)
        for _ in range(count):
            time.sleep(interval_s)
            app.call_soon_threadsafe(lambda payload=payload: apply_fake_payload(kind, payload))

    threading.Thread(target=worker, name=f"fake-reinject-{kind}", daemon=True).start()


