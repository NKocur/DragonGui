def generated_attitude(t: float) -> tuple[float, float, float]:
    pitch = math.sin(t * 0.72) * 28.0
    roll = math.sin(t * 0.48 + 0.7) * 42.0
    yaw = (t * 28.0) % 360.0
    return pitch, roll, yaw


def generated_translation(t: float) -> tuple[float, float]:
    x = math.sin(t * 0.42) * 5.8 + math.sin(t * 1.15) * 1.4
    y = math.cos(t * 0.36 + 0.6) * 4.6 + math.sin(t * 0.85) * 1.1
    return x, y


def attitude_worker() -> None:
    period = 1.0 / max(float(args.attitude_fps), 1.0)
    start = time.perf_counter()
    next_frame = start

    while attitude._live() is None and not attitude_stop_event.wait(0.01):
        pass

    while not attitude_stop_event.is_set():
        now = time.perf_counter()
        if now < next_frame:
            attitude_stop_event.wait(next_frame - now)
            continue

        pitch, roll, yaw = generated_attitude(now - start)
        state["pitch"] = pitch
        state["roll"] = roll
        state["yaw"] = yaw
        try:
            attitude.set_orientation(pitch=pitch, roll=roll, yaw=yaw)
        except RuntimeError:
            break

        next_frame += period
        if next_frame < now - period:
            next_frame = now + period


def translation_worker() -> None:
    period = 1.0 / max(float(args.translation_fps), 1.0)
    label_period = 1.0 / max(float(args.translation_label_fps), 0.25)
    start = time.perf_counter()
    next_frame = start
    next_label = start

    while translation_trace._live() is None and not translation_stop_event.wait(0.01):
        pass

    while not translation_stop_event.is_set():
        now = time.perf_counter()
        if now < next_frame:
            translation_stop_event.wait(next_frame - now)
            continue

        x, y = generated_translation(now - start)
        state["translation_x"] = x
        state["translation_y"] = y
        try:
            translation_trace.set_position(x, y)
            if now >= next_label:
                set_translation_labels(x, y)
                next_label = now + label_period
        except RuntimeError:
            break

        next_frame += period
        if next_frame < now - period:
            next_frame = now + period


def stream_worker() -> None:
    global stream_proc
    try:
        stream_proc = subprocess.Popen(stream_cmd, stdout=subprocess.PIPE)
    except FileNotFoundError:
        app.call_soon_threadsafe(lambda: set_status("v4l2-ctl was not found"))
        return
    except OSError as exc:
        app.call_soon_threadsafe(lambda exc=exc: set_status(f"stream start failed: {exc}"))
        return

    try:
        assert stream_proc.stdout is not None
        while not stop_event.is_set():
            frame_data = stream_proc.stdout.read(frame_bytes)
            if len(frame_data) != frame_bytes:
                state["last_error"] = "incomplete frame"
                app.call_soon_threadsafe(lambda: set_status("incomplete frame"))
                break

            raw = np.frombuffer(frame_data, dtype=np.uint16, count=frame_words)
            try:
                payload = make_phase_payload(raw)
            except Exception as exc:  # pragma: no cover - live hardware path
                state["last_error"] = str(exc)
                app.call_soon_threadsafe(lambda exc=exc: set_status(f"frame error: {exc}"))
                continue

            scatter.enqueue_prepared_points(payload, coalesce=True, include_metadata=False)
            state["frames"] += 1
            state["last_pack_ms"] = payload.pack_ms
            state["last_points"] = payload.point_count
            if state["frames"] == 1 or state["frames"] % 10 == 0:
                app.call_soon_threadsafe(update_metrics)
    finally:
        if stream_proc is not None:
            stream_proc.terminate()
            try:
                stream_proc.wait(timeout=1.0)
            except subprocess.TimeoutExpired:
                stream_proc.kill()
        stream_proc = None


def start_stream() -> None:
    global stream_thread
    if stream_thread is not None and stream_thread.is_alive():
        return
    stop_event.clear()
    stream_thread = threading.Thread(target=stream_worker, name="v4l2-phase-stream", daemon=True)
    stream_thread.start()
    status.set_value("stream starting")


def stop_stream() -> None:
    stop_event.set()
    if stream_proc is not None:
        stream_proc.terminate()
    status.set_value("stream stopping")


