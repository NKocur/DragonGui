def sample_colormap_numpy(name: str, t: "numpy.ndarray") -> "numpy.ndarray":  # type: ignore[name-defined]
    """Map an array of t values in [0, 1] through a named colormap.

    Returns an (N, 3) float32 array of RGB values in [0, 1].
    Requires NumPy.
    """
    import numpy as np

    cpts = _TABLES.get(name.strip().lower(), _TABLES["viridis"])
    cpts_arr = np.array(cpts, dtype=np.float32)
    n = len(cpts_arr) - 1
    t_c = np.clip(t, 0.0, 1.0).astype(np.float32)
    scaled = t_c * n
    idx = np.floor(scaled).astype(np.intp).clip(0, n - 1)
    frac = (scaled - idx).reshape(-1, 1)
    a = cpts_arr[idx]
    b = cpts_arr[np.minimum(idx + 1, n)]
    return (a + (b - a) * frac).astype(np.float32)
